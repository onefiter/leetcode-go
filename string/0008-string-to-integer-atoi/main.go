package atoi

import "math"

// 8. 字符串转换整数 (atoi)
// https://leetcode.cn/problems/string-to-integer-atoi/
// 请你来实现一个 myAtoi(string s) 函数，将字符串转换成一个 32 位有符号整数。
// 规则：
//  1. 读入字符串并丢弃无用的前导空格；
//  2. 检查下一个字符（如果还未到末尾）是 '+' 还是 '-'，确定正负号，默认为正；
//  3. 读入连续的数字字符，直到遇到非数字字符或到达末尾；
//  4. 将前面读到的数字转为整数，没有读到数字则为 0；
//  5. 如果超出 32 位有符号整数范围 [-2^31, 2^31-1]，则裁剪到边界值。
//
// 例如 "42" -> 42；"   -42" -> -42；"4193 with words" -> 4193；
// "words and 987" -> 0；"-91283472332" -> -2147483648（下溢裁剪）。
//
// 一句话理解题意：按「跳空格 → 读符号 → 读数字 → 溢出裁剪」四步顺序解析。
//
// 核心思路：顺序扫描，一次通过。累加过程中实时判断是否会溢出 int32，
// 一旦越界立即返回对应边界值。

const (
	intMax = math.MaxInt32 // 2147483647
	intMin = math.MinInt32 // -2147483648
)

// myAtoi 【解法1】顺序状态扫描 + 溢出裁剪 ⭐ 最优方案
// 思路：依次跳过前导空格、解析可选符号、累加数字，
// 每累加一位前判断是否会超出 int32 范围，超出即裁剪返回。
// 时间复杂度 O(n)：至多遍历一遍字符串。
// 空间复杂度 O(1)。
func myAtoi(s string) int {
	i, n := 0, len(s)
	// 1. 跳过前导空格
	for i < n && s[i] == ' ' {
		i++
	}
	// 2. 解析符号
	sign := 1
	if i < n && (s[i] == '+' || s[i] == '-') {
		if s[i] == '-' {
			sign = -1
		}
		i++
	}
	// 3. 读入数字并累加，4. 实时判断溢出
	res := 0
	for i < n && s[i] >= '0' && s[i] <= '9' {
		d := int(s[i] - '0')
		// 若 res*10+d 会超过 intMax，则正数溢出返回 intMax，负数溢出返回 intMin。
		if res > (intMax-d)/10 {
			if sign == 1 {
				return intMax
			}
			return intMin
		}
		res = res*10 + d
		i++
	}
	return sign * res
}
